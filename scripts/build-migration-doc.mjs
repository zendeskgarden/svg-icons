/**
 * Generates `MIGRATION.md`, the human-readable v8 to v9 icon name reference,
 * from `codemods/v9/codemod-map.json` — the same data the import codemod
 * uses, so the document cannot drift from the codemod. `npm test` regenerates
 * the file and fails on any uncommitted difference.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MAP_URL = new URL('../codemods/v9/codemod-map.json', import.meta.url);
const DOC_URL = new URL('../MIGRATION.md', import.meta.url);

const SVG_SUFFIX = /\.svg$/u;

/**
 * @param {string} name A v8 icon file name.
 * @param {string} target The v9 icon file name it maps to.
 * @param {Map<string, number>} sourceCounts The number of v8 names per v9 file.
 * @returns {string} The change description for the migration table.
 */
function changeLabel(name, target, sourceCounts) {
  const merged = sourceCounts.get(target) > 1;

  if (name === target) {
    return merged ? 'Unchanged (merged)' : 'Unchanged';
  }

  return merged ? 'Renamed (merged)' : 'Renamed';
}

/**
 * @param {object} data The parsed `codemod-map.json` contents.
 * @param {Record<string, string>} data.map v8 icon file name to v9 icon file name.
 * @param {string[]} data.unmapped v8 icon file names with no v9 equivalent.
 * @returns {string} The `MIGRATION.md` contents.
 */
export function renderMigrationDoc({ map, unmapped }) {
  const entries = Object.entries(map).sort(([a], [b]) => a.localeCompare(b));
  const sourceCounts = new Map();

  for (const target of Object.values(map)) {
    sourceCounts.set(target, (sourceCounts.get(target) ?? 0) + 1);
  }

  const rows = entries.map(([name, target]) => {
    const v8 = name.replace(SVG_SUFFIX, '');
    const v9 = target.replace(SVG_SUFFIX, '');

    return `| \`${v8}\` | \`${v9}\` | ${changeLabel(name, target, sourceCounts)} |`;
  });

  const removedRows = unmapped
    .slice()
    .sort((a, b) => a.localeCompare(b))
    .map(name => `| \`${name.replace(SVG_SUFFIX, '')}\` | Removed — no v9 equivalent |`);

  return `<!-- Generated by scripts/build-migration-doc.mjs from codemods/v9/codemod-map.json. -->
<!-- Do not edit by hand; run \`npm run build:migration-doc\` instead. -->

# Migrating from v8 to v9

Version 9 replaces the \`src/12/\` and \`src/16/\` folders with a flat set of
20px icons at \`src/<name>.svg\`. Sprite IDs change from
\`zd-svg-icon-12-<name>\` and \`zd-svg-icon-16-<name>\` to
\`zd-svg-icon-<name>\`.

The [import codemod](README.md#migrating-from-v8) rewrites imports
automatically. Use this reference for the cases the codemod only reports:
PostCSS \`svg-load()\` calls, \`.mdx\` files, string literals, dynamic
\`import()\`/\`require()\` calls, and sprite ID references.

## What changed

- ${entries.length} of ${entries.length + unmapped.length} v8 icon names have a v9
  equivalent; ${unmapped.length} are removed (see below).
- Stroke/fill pairs and duplicate metaphors collapse: ${entries.length} v8 names
  point to ${sourceCounts.size} v9 files. "Merged" rows share their v9 file with
  other v8 icons; if you toggled between a stroke and a fill variant for a
  selected state, that visual difference is gone.
- \`src/12/<name>.svg\` and \`src/16/<name>.svg\` map to the same
  \`src/<name>.svg\`.
- Sizes: rewritten 12px imports get a codemod TODO comment — set the size
  explicitly. Rewritten 16px imports render at 20px unless a size is set.
- Icons that are new in v9 (no v8 counterpart) are not listed here.

## Removed icons

| v8 icon                         | Status                        |
| ------------------------------- | ----------------------------- |
${removedRows.join('\n')}

The codemod reports these imports without touching them. Choose an alternative
from the table below, or stay on v8 until a replacement lands.

## Name changes

| v8 (\`src/12/\` and \`src/16/\`) | v9 (\`src/\`) | Change |
| ------------------------------ | ------------ | ------ |
${rows.join('\n')}
`;
}

/**
 * Regenerate `MIGRATION.md` from `codemods/v9/codemod-map.json`.
 *
 * @param {object} [io] Injectable I/O, used by tests.
 * @param {string} [io.mapContents] The `codemod-map.json` contents.
 * @param {Function} [io.writeImpl] The file writer.
 * @returns {string} The generated document.
 */
export function main({
  mapContents = readFileSync(MAP_URL, 'utf8'),
  writeImpl = (path, contents) => writeFileSync(path, contents)
} = {}) {
  const document = renderMigrationDoc(JSON.parse(mapContents));

  writeImpl(DOC_URL, document);

  return document;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
